// Helper: get compliance data by state name or abbreviation
export function getStateCompliance(stateInput: string): StateCompliance | null {
  const cleaned = stateInput.trim();
  // Try abbreviation match
  const byAbbr = stateComplianceData[cleaned.toUpperCase()];
  if (byAbbr) return byAbbr;
  // Try full name match
  const byName = Object.values(stateComplianceData).find(
    (s) => s.state.toLowerCase() === cleaned.toLowerCase()
  );
  return byName || null;
}

export const US_STATES = Object.values(stateComplianceData).map((s) => ({
  abbr: s.abbr,
  name: s.state,
}));
